const strings = { en, vi };

export function st(key: Key, ...params: (string | number)[]): string {
  const template = strings[getLang()][key];
  return params.reduce<string>((text, value, i) => text.split(`{${i}}`).join(String(value)), template);
}

export function levelLabel(level: LessonLevel, short = false): string {
  if (short) return st(level === 'kids' ? 'levelShortKids' : level === 'mid' ? 'levelShortMid' : 'levelShortAdvanced');
  return st(level === 'kids' ? 'levelKids' : level === 'mid' ? 'levelMid' : 'levelAdvanced');
}
